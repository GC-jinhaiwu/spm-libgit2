# libgit2 (this repository) with HTTPS via OpenSSL and SSH via libssh2.
# The headers ship with a module map so Swift code can `import Clibgit2`.

MODULE=Clibgit2

# Writes <include>/Clibgit2.h, pulling in git2.h and every git2/sys header,
# plus the module map. The header is declared with `header`, not
# `umbrella header`: SwiftPM may merge the headers of all binary targets
# into one include directory, and an umbrella would then warn about every
# libssh2 and OpenSSL header it does not cover.
write_module_map() {
    local include=$1
    {
        echo "/* Generated by script/spm/build.sh: module header for $MODULE. */"
        echo "#ifndef ${MODULE}_MODULE_H"
        echo "#define ${MODULE}_MODULE_H"
        echo '#include "git2.h"'
        (cd "$include" && find git2 -name '*.h' ! -name stdint.h | LC_ALL=C sort) | sed 's|.*|#include "&"|'
        echo "#endif"
    } > "$include/$MODULE.h"
    cat > "$include/module.modulemap" <<MAP
module $MODULE {
    header "$MODULE.h"
    export *
    link "iconv"
}
MAP
}

build_libgit2() {
    local slice
    if [ "$PACKAGE_ONLY" = 0 ]; then
        for slice in $SLICES; do
            log "libgit2: $slice"
            openssl_cmake_flags "$slice"
            # HAVE_LIBSSH2_MEMORY_CREDENTIALS is preset because cmake's probe
            # cannot link the static libssh2 without OpenSSL; libssh2 has had
            # libssh2_userauth_publickey_frommemory since 1.2.2.
            cmake_build libgit2 "$slice" "$REPO_ROOT" "${OPENSSL_CMAKE_FLAGS[@]}" \
                "-DLIBSSH2_INCLUDE_DIR=$OUT/libssh2/$slice/include" \
                "-DLIBSSH2_LIBRARY=$OUT/libssh2/$slice/lib/libssh2.a" \
                -DHAVE_LIBSSH2_MEMORY_CREDENTIALS=1 \
                -DPKG_CONFIG_EXECUTABLE=/usr/bin/false \
                -DBUILD_SHARED_LIBS=OFF \
                -DBUILD_TESTS=OFF \
                -DBUILD_CLI=OFF \
                -DBUILD_EXAMPLES=OFF \
                -DUSE_SSH=libssh2 \
                -DUSE_HTTPS=OpenSSL \
                -DUSE_BUNDLED_ZLIB=ON
        done
    fi
    for slice in $SLICES; do
        write_module_map "$OUT/libgit2/$slice/include"
    done
    make_xcframework "$MODULE" libgit2 libgit2.a yes
}
