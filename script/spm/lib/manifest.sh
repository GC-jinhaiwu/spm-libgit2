# Package.swift generation. Every target is a binary target pointing at a
# zip attached to the GitHub release named by the tag.

PACKAGE_TARGETS="Clibgit2 libssh2 libssl libcrypto"

# owner/repo of the GitHub repository hosting the releases.
github_repository() {
    if [ -n "${GITHUB_REPOSITORY:-}" ]; then
        echo "$GITHUB_REPOSITORY"
    else
        git -C "$REPO_ROOT" remote get-url origin |
            sed -E 's#^(git@github\.com:|https://github\.com/)##; s#\.git$##'
    fi
}

zip_checksum() {
    if command -v swift > /dev/null; then
        swift package compute-checksum "$1"
    else
        shasum -a 256 "$1" | cut -d ' ' -f 1
    fi
}

write_manifest() {
    local tag=$1 repo name
    repo=$(github_repository)
    for name in $PACKAGE_TARGETS; do
        [ -f "$DIST/$name.zip" ] || die "$DIST/$name.zip is missing; build first"
    done
    {
        cat <<HEADER
// swift-tools-version:5.3
//
// Generated by "script/spm/build.sh manifest $tag". Edit that script, not
// this file: the checksums must match the zips attached to the release.

import PackageDescription

let release = "$tag"
let downloads = "https://github.com/$repo/releases/download/\\(release)"

/// A prebuilt XCFramework attached to the GitHub release above.
func prebuilt(_ name: String, checksum: String) -> Target {
    .binaryTarget(name: name, url: "\\(downloads)/\\(name).zip", checksum: checksum)
}

let package = Package(
    name: "libgit2",
    platforms: [.iOS(.v13), .macOS(.v10_15)],
    products: [
        .library(name: "libgit2", targets: ["Clibgit2", "libssh2", "libssl", "libcrypto"]),
    ],
    targets: [
HEADER
        for name in $PACKAGE_TARGETS; do
            printf '        prebuilt("%s", checksum: "%s"),\n' "$name" "$(zip_checksum "$DIST/$name.zip")"
        done
        printf '    ]\n)\n'
    } > "$REPO_ROOT/Package.swift"
    log "wrote Package.swift for https://github.com/$repo/releases/tag/$tag"
}
